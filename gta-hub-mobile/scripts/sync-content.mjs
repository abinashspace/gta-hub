#!/usr/bin/env node
/**
 * Builds the mobile app's bundled library from the site's generated data.
 *
 *   docs/data/games/*.json  -> per game records with resolved image paths
 *   content/games.json      -> game index (title, year, accent, platforms…)
 *
 * Output: src/data/library.json — one import, no network needed for content.
 * Run from the repo root:  node gta-hub-mobile/scripts/sync-content.mjs
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const mobileRoot = path.resolve(here, '..');
const repoRoot = path.resolve(mobileRoot, '..');

const SECTIONS = [
  'characters',
  'missions',
  'vehicles',
  'weapons',
  'cheats',
  'locations',
  'collectibles',
];

const index = JSON.parse(await readFile(path.join(repoRoot, 'content', 'games.json'), 'utf8'));
const site = JSON.parse(await readFile(path.join(repoRoot, 'content', 'site.json'), 'utf8'));

const games = [];
for (const entry of index.games) {
  const file = path.join(repoRoot, 'docs', 'data', 'games', `${entry.slug}.json`);
  if (!existsSync(file)) {
    console.warn(`skip ${entry.slug}: no generated data`);
    continue;
  }
  const data = JSON.parse(await readFile(file, 'utf8'));
  const sections = {};
  for (const section of SECTIONS) {
    const source = data[section];
    if (!source) continue;
    sections[section] = {
      coverage: source.coverage ?? 'partial',
      items: source.items ?? [],
    };
  }
  games.push({
    slug: entry.slug,
    order: entry.order,
    title: entry.title,
    shortTitle: entry.short_title,
    year: entry.year,
    released: entry.released,
    type: entry.type,
    status: entry.status,
    platforms: entry.platforms ?? [],
    cities: entry.cities ?? [],
    setting: entry.setting ?? '',
    developer: entry.developer ?? '',
    publisher: entry.publisher ?? '',
    protagonists: entry.protagonists ?? [],
    accent: entry.accent ?? '#f5c518',
    notes: entry.notes ?? '',
    images: data.meta?.images ?? {},
    counts: data.meta?.counts ?? {},
    coverage: data.meta?.coverage ?? {},
    sections,
  });
}

games.sort((a, b) => a.order - b.order);

const library = {
  generated: new Date().toISOString(),
  baseUrl: site.base_url,
  title: site.title,
  tagline: site.tagline,
  games,
};

const outDir = path.join(mobileRoot, 'src', 'data');
await mkdir(outDir, { recursive: true });
const outFile = path.join(outDir, 'library.json');
await writeFile(outFile, JSON.stringify(library));

// Static require map so every game's art is bundled and available offline.
const artLines = games
  .filter((g) => existsSync(path.join(mobileRoot, 'assets', 'art', 'cover', `${g.slug}.jpg`)))
  .map((g, i) => `  '${g.slug}': require('../../assets/art/cover/${g.slug}.jpg'),${i === 0 ? '' : ''}`)
  .join('\n');
const heroLines = games
  .filter((g) => existsSync(path.join(mobileRoot, 'assets', 'art', 'hero', `${g.slug}.jpg`)))
  .map((g) => `  '${g.slug}': require('../../assets/art/hero/${g.slug}.jpg'),`)
  .join('\n');
await writeFile(
  path.join(outDir, 'art.ts'),
  `/* Generated by scripts/sync-content.mjs — do not edit. */\n` +
    `import type { ImageSourcePropType } from 'react-native';\n\n` +
    `export const coverArt: Record<string, ImageSourcePropType> = {\n${artLines}\n};\n\n` +
    `export const heroArt: Record<string, ImageSourcePropType> = {\n${heroLines}\n};\n`
);

const records = games.reduce(
  (sum, g) => sum + SECTIONS.reduce((n, s) => n + (g.sections[s]?.items.length ?? 0), 0),
  0
);
console.log(
  `library.json: ${games.length} games, ${records} records, ${(JSON.stringify(library).length / 1024).toFixed(0)} KB`
);
